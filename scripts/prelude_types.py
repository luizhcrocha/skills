#!/usr/bin/env python3
"""Write skills/productivity/coordinator/prelude.d.ts, tstack's copy of the declarations a moved team's programs are
written against: the fleet repo's preludeTypes (packages/ledger/src/prelude.ts), the text `fleet-run --types` prints.
The fleet repo owns them; this copy is generated, never edited, so PROGRAMS.md can point at a file an agent reads with
no host service running, and scripts/tests/test_prelude_types.py typechecks PROGRAMS.md's worked calls against it.

    prelude_types.py [CHECKOUT]   read preludeTypes from a fleet checkout ($TSTACK_FLEET_CHECKOUT, else the pinned
                                  ~/repos/luizhcrocha/fleet-live), through Node 24
    prelude_types.py --stdin      read what `fleet-run --types` printed, on stdin
    prelude_types.py --check ...  write nothing; exit 1 when the copy differs from the source
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "skills" / "productivity" / "coordinator" / "prelude.d.ts"
SOURCE = "packages/ledger/src/prelude.ts"
HEADER = ("// Generated by scripts/prelude_types.py from the fleet repo's packages/ledger/src/prelude.ts (preludeTypes):\n"
          "// the declarations `fleet-run --types` prints. Do not edit: run `python3 scripts/prelude_types.py` on a fleet\n"
          "// checkout, or pipe `fleet-run --types` into it with --stdin.\n")
READ = ("const { pathToFileURL } = await import('node:url');"
        "const m = await import(pathToFileURL(process.argv[1]).href);"
        "process.stdout.write(m.preludeTypes);")


def checkout() -> Path:
    """The fleet checkout the tests and this script read: $TSTACK_FLEET_CHECKOUT, else the pinned fleet-live."""
    return Path(os.environ.get("TSTACK_FLEET_CHECKOUT") or Path.home() / "repos/luizhcrocha/fleet-live")


def from_checkout(repo: Path) -> str:
    """preludeTypes from the fleet checkout at repo; raises FileNotFoundError when it has no prelude."""
    source = repo / SOURCE
    if not source.is_file():
        raise FileNotFoundError(f"no {SOURCE} in {repo}")
    done = subprocess.run(["node", "--input-type=module", "-e", READ, str(source)], capture_output=True, text=True,
                          check=True, timeout=60)
    return done.stdout


def render(types: str) -> str:
    """The checked-in file for the declarations types."""
    return HEADER + types


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("checkout", nargs="?", type=Path)
    parser.add_argument("--stdin", action="store_true", help="read `fleet-run --types` output on stdin")
    parser.add_argument("--check", action="store_true", help="exit 1 when the copy is stale; write nothing")
    args = parser.parse_args()
    types = sys.stdin.read() if args.stdin else from_checkout(args.checkout or checkout())
    want = render(types)
    have = OUT.read_text() if OUT.exists() else ""
    if args.check:
        if have != want:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/prelude_types.py", file=sys.stderr)
            return 1
        return 0
    if have != want:
        OUT.write_text(want)
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
