"""skills/productivity/coordinator/prelude.d.ts against its source and its readers. The copy is the fleet repo's
preludeTypes, generated by scripts/prelude_types.py: stale when it differs from a fleet checkout's ($TSTACK_FLEET_CHECKOUT,
else the pinned ~/repos/luizhcrocha/fleet-live; the check skips without one). PROGRAMS.md's worked calls typecheck
against the copy, as the JavaScript they are, so a call the declarations do not allow fails here with no fleet repo;
GAPS are the calls the cloud takes that the declarations do not declare yet, each a fix on the fleet's side."""

import json
import re
import shutil
import subprocess
import tempfile
import unittest
from importlib.machinery import SourceFileLoader
from importlib.util import module_from_spec, spec_from_loader
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# PROGRAMS.md and its on-demand parts (PROGRAMS-CARDS.md, PROGRAMS-WORK.md).
PROGRAMS = sorted((ROOT / "skills" / "productivity" / "coordinator").glob("PROGRAMS*.md"))

# tsc's message for each gap, and what the fleet's declarations lack. A gap that no longer shows is closed: drop it here,
# and the words in PROGRAMS.md that warn of it.
GAPS = {
    "'supersedes' does not exist in type": "Card declares no supersedes (PROGRAMS-CARDS.md's Change my answer warns of it)",
}

TSCONFIG = {"compilerOptions": {"allowJs": True, "checkJs": True, "noEmit": True, "strict": False,
                                "target": "es2022", "lib": ["es2022"], "module": "esnext", "types": []},
            "include": ["*.js", "prelude.d.ts"]}


def load_generator():
    loader = SourceFileLoader("prelude_types", str(ROOT / "scripts" / "prelude_types.py"))
    module = module_from_spec(spec_from_loader(loader.name, loader))
    loader.exec_module(module)
    return module


GEN = load_generator()


def tsc():
    """The fleet's pinned tsc (fleet/package.json), once `just _deps-fleet` installed it, else None: another version
    reports other errors on the same JavaScript."""
    pinned = ROOT / "fleet" / "node_modules" / ".bin" / "tsc"
    return str(pinned) if pinned.is_file() else None

class CopyTest(unittest.TestCase):
    def test_the_copy_is_the_fleets_prelude_types(self):
        if not shutil.which("node"):
            self.skipTest("no node on PATH: the fleet's prelude is read through Node 24")
        try:
            types = GEN.from_checkout(GEN.checkout())
        except FileNotFoundError as missing:
            self.skipTest(f"{missing}: set TSTACK_FLEET_CHECKOUT to a fleet checkout to compare the copy with it")
        self.assertTrue(GEN.OUT.read_text() == GEN.render(types),
                        "prelude.d.ts is stale: run python3 scripts/prelude_types.py")


class WorkedCallsTypecheckTest(unittest.TestCase):
    def test_every_worked_call_typechecks_against_the_copy(self):
        compiler = tsc()
        if compiler is None:
            self.skipTest("no fleet/node_modules/.bin/tsc: run just _deps-fleet")
        bodies = [b for p in PROGRAMS for b in re.findall(r"```ts\n(.*?)```", p.read_text(), re.S)]
        self.assertGreaterEqual(len(bodies), 6)
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp)
            shutil.copy(GEN.OUT, work / "prelude.d.ts")
            (work / "tsconfig.json").write_text(json.dumps(TSCONFIG))
            for i, body in enumerate(bodies, 1):
                (work / f"call{i:02}.js").write_text(f"export {{}};\nasync function program() {{\n{body}}}\n")
            done = subprocess.run([compiler, "-p", str(work / "tsconfig.json")], capture_output=True, text=True,
                                  check=False, timeout=120)
        errors = [line for line in done.stdout.splitlines() if ": error TS" in line]
        self.assertEqual(done.returncode != 0, bool(errors), done.stdout + done.stderr)
        unknown = [e for e in errors if not any(gap in e for gap in GAPS)]
        self.assertEqual(unknown, [], "a worked call the declarations do not allow: fix the call, or the fleet's "
                                      "preludeTypes and then prelude.d.ts")
        closed = [why for gap, why in GAPS.items() if not any(gap in e for e in errors)]
        self.assertEqual(closed, [], "the declarations allow these now: drop them from GAPS and PROGRAMS.md")


if __name__ == "__main__":
    unittest.main()
